import { generateKeyPairSync, verify } from 'node:crypto';
import { describe, expect, it, vi } from 'vitest';
import {
  StationMembershipClient,
  StationMembershipSigner,
  createStationMembershipTransport,
  parseStationAdmissionResponse,
  parseStationMarker,
  stationAdmissionId,
  stationHash,
  stationPath,
  type StationAdmissionRequest,
  type StationActor,
} from './station-membership.js';

const uuid = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const actor: StationActor = {
  tenantId: uuid(1),
  canonicalUserId: uuid(2),
  providerMappingId: uuid(3),
  playerId: 'synthetic-player',
};
const request: StationAdmissionRequest = {
  contractVersion: 1,
  operationId: uuid(4),
  requestSha256: 'sha256:' + 'a'.repeat(64),
  activity: { kind: 'GAME', id: uuid(5) },
  stationId: 'synthetic-studio',
};
const response = () => ({
  contractVersion: 1,
  operationId: request.operationId,
  admission: {
    outcome: 'ADMITTED',
    admissionId: stationAdmissionId(actor.tenantId, request.operationId),
    communityId: 'synthetic-community',
    membershipEpoch: 2,
    reason: 'ELIGIBLE',
    bindingSha256: 'sha256:' + 'b'.repeat(64),
  },
  replayed: false,
});
const correlationId = 'station-test-correlation';
const envelope = { delegation: 'synthetic.delegation.only', correlationId };
const key = generateKeyPairSync('rsa', { modulusLength: 2048 });
const pem = key.privateKey.export({ format: 'pem', type: 'pkcs8' }).toString();
const signer = new StationMembershipSigner({
  privateKeyPem: pem,
  keyId: 'test-key',
  issuer: 'synthetic-owner',
  audience: 'synthetic-station',
  now: () => 1000000,
});

describe('private station owner protocol', () => {
  it('matches frozen LK owner canonical bytes and deterministic admission ID', () => {
    // Independently generated by LK stationMembershipLifetime.mjs owner implementation.
    expect(stationHash('station-membership-body:v1', request)).toBe(
      'sha256:8e000a512169a69637c93125506799f92d2d1987f022da479e6e927f3047ecdd',
    );
    expect(stationAdmissionId(actor.tenantId, request.operationId)).toBe(
      '1fa13cf4-9c6c-8360-976c-cc5cdf8ffc3d',
    );
  });
  it('signs distinct admission and persisted-fact claims, exact path/body and no session in delivery', () => {
    const admission = signer.issue({
      mode: 'admission',
      actor,
      request,
      sessionId: uuid(6),
      correlationId,
    });
    const parts = admission.split('.');
    expect(
      verify(
        'RSA-SHA256',
        Buffer.from(parts.slice(0, 2).join('.')),
        key.publicKey,
        Buffer.from(parts[2]!, 'base64url'),
      ),
    ).toBe(true);
    const claims = JSON.parse(Buffer.from(parts[1]!, 'base64url').toString()) as unknown;
    expect(claims).toMatchObject({
      aud: 'synthetic-station',
      iat: 1000,
      exp: 1030,
      sid: uuid(6),
      fresh_operation: true,
      adoption_version: 1,
      path: stationPath(request.operationId, 'admission'),
      body_sha256: stationHash('station-membership-body:v1', request),
      scope: 'communities.station-membership.admit',
    });
    const delivery = signer.issue({
      mode: 'confirmation',
      actor,
      correlationId,
      caller: 'lk2-worker',
      request: {
        contractVersion: 1,
        operationId: request.operationId,
        admissionId: response().admission.admissionId,
        admissionBindingSha256: response().admission.bindingSha256,
        confirmation: {
          kind: 'GAME_PARTICIPATION',
          generationId: uuid(8),
          activityId: request.activity.id,
        },
      },
    });
    const deliveryClaims = JSON.parse(
      Buffer.from(delivery.split('.')[1]!, 'base64url').toString(),
    ) as unknown;
    expect(deliveryClaims).toMatchObject({
      caller: 'lk2-worker',
      persisted_fact: true,
      scope: 'communities.station-membership.confirm',
    });
    for (const field of [
      'sid',
      'fresh_operation',
      'actor_token',
      'actor_token_sha256',
      'adoption_version',
    ])
      expect(deliveryClaims).not.toHaveProperty(field);
    expect(JSON.parse(Buffer.from(parts[0]!, 'base64url').toString())).toEqual({
      alg: 'RS256',
      kid: 'test-key',
      typ: 'phub-station-membership-delegation+jwt',
    });
  });
  it('rejects body authority injection and wrong actor/admission identity', () => {
    expect(() =>
      signer.issue({
        mode: 'admission',
        actor,
        request: { ...request, actor } as StationAdmissionRequest,
        sessionId: uuid(6),
        correlationId,
      }),
    ).toThrow();
    expect(() =>
      parseStationAdmissionResponse({ ...response(), operationId: uuid(9) }, actor, request),
    ).toThrow();
    expect(() =>
      parseStationAdmissionResponse(
        { ...response(), admission: { ...response().admission, admissionId: uuid(9) } },
        actor,
        request,
      ),
    ).toThrow();
    expect(() =>
      parseStationAdmissionResponse(
        { ...response(), admission: { ...response().admission, membershipEpoch: null } },
        actor,
        request,
      ),
    ).toThrow();
    expect(() =>
      parseStationMarker({
        version: 1,
        outcome: 'NO_ENROLLMENT',
        reason: 'DISABLED',
        refresh: true,
      }),
    ).toThrow();
  });
  it('accepts immutable missing selector negative and rejects success-shaped negatives', () => {
    const no = {
      ...response(),
      admission: {
        ...response().admission,
        outcome: 'NO_ENROLLMENT',
        reason: 'STATION_COMMUNITY_MISSING',
        communityId: null,
        membershipEpoch: null,
      },
    };
    expect(parseStationAdmissionResponse(no, actor, request).admission.outcome).toBe(
      'NO_ENROLLMENT',
    );
    expect(() =>
      parseStationAdmissionResponse(
        { ...no, admission: { ...no.admission, outcome: 'ADMITTED' } },
        actor,
        request,
      ),
    ).toThrow();
  });
  it('sends one bounded owner POST with only dedicated delegation and no user credential', async () => {
    const fetcher = vi.fn(() => Promise.resolve(new Response(JSON.stringify(response()))));
    const client = new StationMembershipClient({
      baseUrl: 'https://owner.invalid',
      environment: 'production',
      timeoutMs: 100,
      fetchImplementation: fetcher,
    });
    await client.admit(request, actor, envelope);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(fetcher.mock.calls[0]).toEqual([
      `https://owner.invalid${stationPath(request.operationId, 'admission')}`,
      expect.objectContaining({
        redirect: 'error',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-Station-Membership-Delegation': envelope.delegation,
          'X-Correlation-ID': correlationId,
        },
      }),
    ]);
  });
  it.each(['timeout', 'oversize', 'malformed', 'wrong-operation', '503'])(
    'never retries %s or treats unknown as enrollment',
    async (mode) => {
      const fetcher = vi.fn(async () => {
        if (mode === 'timeout') return new Promise<Response>(() => {});
        if (mode === 'oversize') return new Response('x'.repeat(8193));
        if (mode === 'malformed') return new Response('{');
        if (mode === '503') return new Response('{}', { status: 503 });
        return new Response(JSON.stringify({ ...response(), operationId: uuid(88) }));
      });
      const client = new StationMembershipClient({
        baseUrl: 'https://owner.invalid',
        environment: 'production',
        timeoutMs: 100,
        fetchImplementation: fetcher,
      });
      await expect(client.admit(request, actor, envelope)).rejects.toThrow(
        'STATION_MEMBERSHIP_UNAVAILABLE',
      );
      expect(fetcher).toHaveBeenCalledTimes(1);
    },
  );
  it('opens circuit after three failures including malformed owner data', async () => {
    const fetcher = vi.fn(() => Promise.resolve(new Response('{}')));
    const client = new StationMembershipClient({
      baseUrl: 'https://owner.invalid',
      environment: 'production',
      timeoutMs: 100,
      fetchImplementation: fetcher,
    });
    for (let i = 0; i < 4; i++)
      await expect(client.admit(request, actor, envelope)).rejects.toThrow();
    expect(fetcher).toHaveBeenCalledTimes(3);
  });
  it('is default off and fails closed for an enabled unprovisioned signer', () => {
    expect(
      createStationMembershipTransport({
        APP_ENV: 'ci',
        GAME_COMMERCIAL_JOIN_OWNER_TIMEOUT_MS: 100,
      }),
    ).toBeUndefined();
    expect(() =>
      createStationMembershipTransport({
        APP_ENV: 'ci',
        GAME_COMMERCIAL_JOIN_OWNER_TIMEOUT_MS: 100,
        LK_STATION_MEMBERSHIP_LIFETIME_ENABLED: true,
      }),
    ).toThrow();
    expect(
      () =>
        new StationMembershipClient({
          baseUrl: 'http://owner.invalid',
          environment: 'production',
          timeoutMs: 100,
        }),
    ).toThrow();
    expect(
      () =>
        new StationMembershipClient({
          baseUrl: 'https://owner.invalid/path',
          environment: 'production',
          timeoutMs: 100,
        }),
    ).toThrow();
  });
});

it('explicit CREATE signed wire matches reviewed LK receiver bytes without changing GAME/TRAINING', () => {
  const createRequest = {
    ...request,
    activity: { kind: 'GAME_CREATE' as const, id: request.activity.id },
  };
  // Independently calculated with LK #280 stationMembershipLifetime.mjs smHash.
  expect(stationHash('station-membership-body:v1', createRequest)).toBe(
    'sha256:e73b5545728cfe3930c38b7ef8ac05b1eb4df4acb35e92ee60d93a111fa84348',
  );
  const jwt = signer.issue({
      mode: 'admission',
      actor,
      request: createRequest,
      sessionId: uuid(6),
      correlationId,
    }),
    parts = jwt.split('.');
  expect(
    verify(
      'RSA-SHA256',
      Buffer.from(parts.slice(0, 2).join('.')),
      key.publicKey,
      Buffer.from(parts[2]!, 'base64url'),
    ),
  ).toBe(true);
  const claims = JSON.parse(Buffer.from(parts[1]!, 'base64url').toString()) as unknown;
  expect(claims).toMatchObject({
    scope: 'communities.station-membership.admit',
    body_sha256: stationHash('station-membership-body:v1', createRequest),
    sid: uuid(6),
    fresh_operation: true,
  });
  const body = {
    contractVersion: 1 as const,
    operationId: request.operationId,
    admissionId: response().admission.admissionId,
    admissionBindingSha256: response().admission.bindingSha256,
    confirmation: {
      kind: 'GAME_CREATE_ORGANIZER' as const,
      generationId: uuid(8),
      activityId: request.activity.id,
    },
  };
  const token = signer.issue({
    mode: 'confirmation',
    actor,
    correlationId,
    caller: 'lk2-worker',
    request: body,
  });
  const factClaims = JSON.parse(
    Buffer.from(token.split('.')[1]!, 'base64url').toString(),
  ) as unknown;
  expect(factClaims).toMatchObject({
    persisted_fact: true,
    body_sha256: stationHash('station-membership-body:v1', body),
  });
  expect(factClaims).not.toHaveProperty('sid');
});
