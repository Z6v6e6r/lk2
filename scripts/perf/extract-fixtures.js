#!/usr/bin/env node
// Builds the stub-API fixtures from the fixtures that already prove the client renders Home, the
// profile and the game list in apps/web/src/App.test.tsx. Copying them by hand would drift from the
// UI contract, so this generator extracts the fixture block and strips its type annotations.
//
// Usage: node scripts/perf/extract-fixtures.js  ->  scripts/perf/fixtures.js
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const source = readFileSync(join(repo, 'apps/web/src/App.test.tsx'), 'utf8');

const start = source.indexOf('const session: AuthenticatedSession = {');
const end = source.indexOf('function createGateway(');
if (start < 0 || end < 0 || end <= start) throw new Error('fixture block not found');

const block = source.slice(start, end);
const exported = (await transform(block, { loader: 'ts', format: 'esm', target: 'node20' })).code;
const names = [
  'session',
  'homeDashboard',
  'homeBase',
  'userProfile',
  'profilePrivacy',
  'upcomingBookings',
  'notificationInbox',
  'notificationPreferences',
  'communityMemberships',
  'bookingPreferences',
  'bookingRecommendations',
  'giftCertificateCatalog',
];

const output = `// Generated by scripts/perf/extract-fixtures.js from apps/web/src/App.test.tsx.
// Do not edit by hand; rerun the generator after changing the UI contract fixtures.
${exported}
export { ${names.join(', ')} };
`;
writeFileSync(join(here, 'fixtures.js'), output);
console.log(`wrote scripts/perf/fixtures.js (${output.length} bytes, ${names.length} fixtures)`);
